/**
 * Oracle Puzzle Modal (Third-Party Web Service Interoperability)
 *
 * Location: frontend/src/components/OraclePuzzleModal.jsx
 * Where it fits: Interactive UI Component. Triggered when catching the Legendary Oracle Fish
 * or when qualifying for level progression.
 *
 * Why (Academic Rubric - Interoperability & Event-Driven Programming):
 * Demonstrates distributed service interoperability with Dr. Marc Conrad's Fish Game API
 * (https://marcconrad.com/uob/fish/).
 * Handles user input events, async Promise events, and audio dispatching.
 */

import { useEffect, useState } from 'react';
import { gameApi } from '../utils/api';
import { soundEngine } from '../utils/sound';
import { SparklesIcon, TrophyIcon } from './Icons';

export default function OraclePuzzleModal({ isOpen, onClose, onPuzzleSuccess }) {
  const [loading, setLoading] = useState(true);
  const [challenge, setChallenge] = useState(null);
  const [userAnswer, setUserAnswer] = useState('');
  const [verifying, setVerifying] = useState(false);
  const [result, setResult] = useState(null);
  const [error, setError] = useState('');

  // Fetch puzzle from Marc Conrad Fish API via our Express Interoperability endpoint
  useEffect(() => {
    if (!isOpen) {
      setChallenge(null);
      setUserAnswer('');
      setResult(null);
      setError('');
      return;
    }

    let active = true;
    setLoading(true);
    setError('');
    setResult(null);

    gameApi
      .getPuzzleChallenge()
      .then((data) => {
        if (active) {
          setChallenge(data);
        }
      })
      .catch((err) => {
        if (active) {
          setError(err.message || 'Failed to connect to Marc Conrad Fish API.');
        }
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
    };
  }, [isOpen]);

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!challenge || userAnswer === '' || verifying) return;

    setVerifying(true);
    setError('');

    try {
      soundEngine.playClick();
      const verification = await gameApi.verifyPuzzle({
        puzzleId: challenge.puzzleId,
        answer: Number(userAnswer),
      });

      setResult(verification);

      if (verification.correct) {
        soundEngine.playLevelUp?.() || soundEngine.playCatch?.('biolume');
        if (onPuzzleSuccess) {
          onPuzzleSuccess(verification.bonusMarks);
        }
      }
    } catch (err) {
      setError(err.message || 'Verification failed.');
    } finally {
      setVerifying(false);
    }
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md animate-fade-in">
      <div className="glass-panel w-full max-w-[560px] rounded-[30px] p-6 sm:p-8 relative overflow-hidden border border-amber-400/40 shadow-[0_0_40px_rgba(251,191,36,0.3)] animate-modal-enter">
        {/* Glowing Top Accent */}
        <div className="absolute top-0 inset-x-12 h-px bg-gradient-to-r from-transparent via-amber-300 to-transparent" />

        {/* Modal Header */}
        <div className="flex items-center gap-3 mb-3">
          <div className="p-2.5 rounded-2xl bg-amber-400/20 border border-amber-400/40 shadow-[0_0_15px_rgba(251,191,36,0.5)]">
            <SparklesIcon className="w-7 h-7 text-amber-300" />
          </div>
          <div>
            <span className="text-[10px] font-bold uppercase tracking-[0.25em] text-amber-300/90">
              Dr. Marc Conrad Fish API Interoperability
            </span>
            <h2 className="text-xl sm:text-2xl font-black text-white tracking-tight">
              Golden Oracle Riddle
            </h2>
          </div>
        </div>

        <p className="text-xs text-slate-300/85 mb-4 leading-relaxed">
          You hooked the legendary <strong className="text-amber-300">Golden Oracle Fish</strong>!
          Solve the visual puzzle generated by the external web service to claim massive bonus marks.
        </p>

        {loading ? (
          <div className="py-12 flex flex-col items-center justify-center gap-3">
            <div className="w-10 h-10 border-3 border-amber-400/30 border-t-amber-400 rounded-full animate-spin" />
            <span className="text-xs text-amber-200/80 font-medium">
              Interoperating with marcconrad.com/uob/fish...
            </span>
          </div>
        ) : error ? (
          <div className="p-4 rounded-2xl bg-rose-500/15 border border-rose-500/30 text-rose-200 text-xs text-center mb-4">
            {error}
          </div>
        ) : challenge ? (
          <div className="flex flex-col items-center">
            {/* Aquarium Viewport */}
            <div className="relative w-full max-w-[420px] rounded-2xl overflow-hidden border-2 border-cyan-400/40 shadow-[inset_0_0_20px_rgba(34,211,238,0.4)] mb-4 bg-gradient-to-b from-sky-600 to-sky-950 p-2 flex items-center justify-center">
              <img
                src={challenge.imageUrl}
                alt="Marc Conrad Fish Game Riddle"
                className="max-h-[200px] w-auto rounded-xl object-contain drop-shadow-[0_4px_12px_rgba(0,0,0,0.6)]"
              />
            </div>

            {/* Result Display */}
            {result ? (
              <div
                className={`w-full p-4 rounded-2xl border text-center mb-4 animate-scale-in ${
                  result.correct
                    ? 'bg-emerald-500/15 border-emerald-400/40 text-emerald-200'
                    : 'bg-rose-500/15 border-rose-500/30 text-rose-200'
                }`}
              >
                <div className="text-base font-bold mb-1">
                  {result.correct ? '🎉 Riddle Solved!' : '❌ Incorrect Riddle Answer'}
                </div>
                <div className="text-xs opacity-90">{result.message}</div>
                {result.correct && (
                  <div className="mt-2 text-xs font-semibold text-amber-300 flex items-center justify-center gap-1">
                    <TrophyIcon className="w-4 h-4" /> +{result.bonusMarks} Legendary Marks Added
                  </div>
                )}
              </div>
            ) : (
              <form onSubmit={handleSubmit} className="w-full flex flex-col items-center gap-3">
                <label className="text-xs text-cyan-200 font-semibold text-center">
                  How many fish are in the picture? (0 - 9)
                </label>
                <div className="flex gap-2 w-full max-w-[280px]">
                  <input
                    type="number"
                    min="0"
                    max="9"
                    step="1"
                    required
                    autoFocus
                    value={userAnswer}
                    onChange={(e) => setUserAnswer(e.target.value)}
                    placeholder="Enter count"
                    className="w-full px-4 py-2.5 rounded-xl bg-slate-900/80 border border-cyan-400/30 text-white text-center text-lg font-bold placeholder:text-slate-500 focus:outline-none focus:border-amber-400 focus:ring-2 focus:ring-amber-400/20"
                  />
                  <button
                    type="submit"
                    disabled={verifying || userAnswer === ''}
                    className="px-5 py-2.5 rounded-xl bg-gradient-to-r from-amber-400 to-amber-500 hover:from-amber-300 hover:to-amber-400 text-slate-950 font-black text-sm tracking-wide shadow-[0_0_15px_rgba(251,191,36,0.4)] disabled:opacity-50 transition-all cursor-pointer"
                  >
                    {verifying ? 'Checking...' : 'Submit'}
                  </button>
                </div>
              </form>
            )}
          </div>
        ) : null}

        {/* Action Button */}
        <div className="mt-5 flex justify-end">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2 rounded-xl text-xs font-semibold text-slate-300 hover:text-white bg-slate-800/60 hover:bg-slate-700/60 border border-slate-700/50 transition-all cursor-pointer"
          >
            {result ? 'Resume Fishing' : 'Dismiss & Continue'}
          </button>
        </div>
      </div>
    </div>
  );
}
